test('fee form uses live dedicated endpoint and shows success', async ({ page }) => {
  await openHome(page)
  const form = page.getByRole('form', { name: 'Get Fee Structure', exact: true })
  await fillBasics(form)
  await form.getByLabel('Interested Stream').selectOption('PCMC')
  await expect(form.getByLabel('Target Exam').locator('option[value="NEET"]')).toHaveCount(0)
  await form.getByLabel('Target Exam').selectOption('JEE')
  const sent = page.waitForResponse(res => res.url().endsWith('/api/leads/fee-structure') && res.request().method() === 'POST')
  await form.getByRole('button', { name: 'Get Fee Structure', exact: true }).click()
  const response = await sent
  expect(response.status()).toBe(201)
  expect(response.request().postDataJSON()).toMatchObject({ studentName: 'Browser Test Student', interestedStream: 'PCMC', targetExam: 'JEE', leadSource: 'website' })
  await expect(form.getByRole('status')).toHaveText('Thanks! Our admissions team will contact you shortly.')
  await expect(form.getByLabel('Student Name')).toHaveValue('')
})
