test('loading, validation, rate-limit and network errors remain readable', async ({ page }) => {
  await openHome(page)
  const form = page.getByRole('form', { name: 'Get Fee Structure', exact: true })
  await fillBasics(form)
  let release
  await page.route('**/api/leads/fee-structure', async route => {
    await new Promise(resolve => { release = resolve })
    await route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ success: false, message: 'Validation failed', errors: [{ field: 'phone', message: 'Enter a valid Indian mobile number' }] }) })
  })
  await form.getByRole('button', { name: 'Get Fee Structure', exact: true }).click()
  await expect(form.getByRole('button', { name: 'Submitting…' })).toBeDisabled()
  await expect.poll(() => !!release).toBe(true)
  release()
  await expect(form.getByRole('alert')).toContainText('Validation failed')
  await expect(form.getByLabel('Mobile Number')).toHaveAttribute('aria-invalid', 'true')
  await page.unroute('**/api/leads/fee-structure')
  await page.route('**/api/leads/fee-structure', route => route.fulfill({ status: 429, contentType: 'application/json', body: JSON.stringify({ success: false, message: 'Too many requests; try again later', errors: [] }) }))
  await form.getByRole('button', { name: 'Get Fee Structure', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('Too many requests')
  await page.unroute('**/api/leads/fee-structure')
  await page.route('**/api/leads/fee-structure', route => route.abort())
  await form.getByRole('button', { name: 'Get Fee Structure', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('Unable to submit')
  await expect(form.getByLabel('Student Name')).toHaveValue('Browser Test Student')
})
