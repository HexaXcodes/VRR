import { test, expect } from '@playwright/test'

for (const width of [375, 768, 1024, 1440]) {
  test(`Why VRR panels and native learner-support anchor at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    const section = page.locator('.why-section')
    const cards = section.getByRole('article')
    await expect(cards).toHaveCount(4)
    for (const [index, title] of ['Integrated Preparation', 'Expert Faculty', 'Testing + Mentoring', 'Student-Centred Learning'].entries()) {
      await expect(cards.nth(index)).toHaveAccessibleName(title)
      await expect(cards.nth(index)).toHaveCSS('background-color', 'rgb(7, 26, 51)')
      await expect(cards.nth(index).getByRole('heading')).toHaveCSS('color', 'rgb(255, 255, 255)')
    }
    await expect(section.getByText('Parent Visibility')).toHaveCount(0)
    await expect(section.getByRole('link', { name: 'View admissions procedure' })).toHaveCount(0)
    const link = section.getByRole('link', { name: 'How VRR supports each learner' })
    const destination = page.locator('#why-student-support')
    await expect(destination).toHaveCount(1)
    expect(await section.evaluate(el => el.nextElementSibling.id)).toBe('why-student-support')
    await expect(link).toHaveAttribute('href', '#why-student-support')
    const url = page.url()
    await link.focus()
    await link.evaluate(el => el.scrollIntoView({ behavior: 'instant', block: 'center' }))
    const previousScroll = await page.evaluate(() => window.scrollY)
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(`${url}#why-student-support`)
    await expect.poll(() => destination.evaluate(el => Math.abs(el.getBoundingClientRect().top - 196))).toBeLessThan(3)
    expect(await page.evaluate(() => window.scrollY)).toBeGreaterThan(previousScroll + 100)
    const assertHeadingClear = async () => expect(await page.evaluate(() => document.querySelector('#student-support-heading').getBoundingClientRect().top > document.querySelector('.vrr-navigation').getBoundingClientRect().bottom)).toBe(true)
    await assertHeadingClear()
    await page.goBack()
    await expect(page).toHaveURL(url)
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeCloseTo(previousScroll, 0)
    await page.goForward()
    await expect(page).toHaveURL(`${url}#why-student-support`)
    await expect.poll(() => destination.evaluate(el => Math.abs(el.getBoundingClientRect().top - 196))).toBeLessThan(3)
    await assertHeadingClear()
    await expect(destination.getByRole('listitem')).toHaveCount(4)
    for (const title of ['Understand', 'Identify', 'Support', 'Progress']) await expect(destination.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await cards.first().focus()
    await page.keyboard.press('Tab')
    await expect(cards.nth(1)).toBeFocused()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await link.click()
    await expect(destination).toBeFocused()
    await assertHeadingClear()
    await expect(destination.getByRole('listitem').first()).toHaveCSS('animation-name', 'none')
    const stages = await destination.getByRole('listitem').evaluateAll(elements => elements.map(el => ({ x: el.offsetLeft, y: el.offsetTop })))
    if (width < 1024) expect(stages.slice(1).every((stage, index) => stage.y > stages[index].y)).toBe(true)
    else expect(stages.every(stage => stage.y === stages[0].y)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const card of await cards.all()) expect(await card.evaluate(el => el.scrollWidth <= el.clientWidth && el.scrollHeight <= el.clientHeight)).toBe(true)
    const boxes = await cards.evaluateAll(elements => elements.map(el => { const rect = el.getBoundingClientRect(); return { x: rect.x, y: rect.y, width: rect.width, height: rect.height } }))
    if (width < 768) {
      expect(boxes.every(box => box.width === boxes[0].width)).toBe(true)
      expect(boxes.slice(1).every((box, index) => box.y >= boxes[index].y + boxes[index].height)).toBe(true)
    } else {
      expect(boxes[0].width).toBe(boxes[3].width)
      expect(boxes[1].width).toBeCloseTo(boxes[2].width, 0)
      expect(boxes[1].y).toBe(boxes[2].y)
    }
    const style = await page.addStyleTag({ content: '.vrr-navigation, .mobile-cta { visibility: hidden; } html { scroll-behavior: auto; }' })
    await section.screenshot({ path: `test-results/why-vrr-${width}.png` })
    await destination.screenshot({ path: `test-results/student-support-${width}.png` })
    await style.evaluate(el => el.remove())
  })
}
